"""Generate the Windows version resource for the packaged exe.

Why this exists: ``EXE()`` in the spec had no ``version=`` argument, so the
built ``AgentTokenRadar.exe`` carried an *empty* version resource. Right-click
-> Properties -> Details showed nothing: no version, no product name, no
publisher. The installer ``Setup.exe`` did carry ``0.0.4.0``, which made the
omission easy to miss -- the file people actually run was the anonymous one.

That is not cosmetic. Windows file identification, add/remove listings that
point at the exe, and enterprise allow-listing by version all read this
resource. A blank one makes the app look unversioned.

The version number is read from ``agent_token_radar.__version__`` rather than
written here, so the project keeps a single source of truth (it is already
mirrored into pyproject.toml and the .iss; a fourth hand-maintained copy is a
fourth thing to forget).

This lives in the package, not in ``build/``, because ``build/`` is gitignored
as a PyInstaller scratch directory -- a build script kept there would be absent
from a fresh clone and the spec would fail on import.

Run via the spec, which calls ``version_file()`` while building.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

PRODUCT_NAME = "Agent Token Radar"
COMPANY_NAME = "agent-token-radar"
FILE_DESCRIPTION = "Agent Token Radar"
COPYRIGHT = "MIT licensed. Third-party brand icons belong to their vendors."
ORIGINAL_FILENAME = "AgentTokenRadar.exe"

#: Where the generated resource is written. Still inside build/ (gitignored,
#: regenerated every build), just not where the generator itself lives.
DEFAULT_OUT = ROOT / "build" / "version_info.txt"


def project_version() -> str:
    """The one version string, read from the package without importing it.

    Importing would pull in FastAPI and the whole adapter tree during a build
    step, which is slow and can fail for reasons unrelated to versioning.
    """
    init = ROOT / "agent_token_radar" / "__init__.py"
    match = re.search(r'^__version__\s*=\s*"([^"]+)"', init.read_text(encoding="utf-8"),
                      re.MULTILINE)
    if not match:
        raise SystemExit(f"could not find __version__ in {init}")
    return match.group(1)


def _version_tuple(version: str) -> tuple[int, int, int, int]:
    """Pad/trim to the four 16-bit fields a Windows version resource needs."""
    parts: list[int] = []
    for chunk in version.split("."):
        # A suffix like "0-rc1" must not crash the build; take the leading digits.
        digits = re.match(r"\d+", chunk.strip())
        parts.append(int(digits.group(0)) if digits else 0)
    parts = (parts + [0, 0, 0, 0])[:4]
    return tuple(parts)  # type: ignore[return-value]


def version_file(out_path: Path | None = None) -> str:
    """Write the resource file and return its path (PyInstaller wants a path)."""
    version = project_version()
    nums = _version_tuple(version)
    out = Path(out_path) if out_path else DEFAULT_OUT
    out.parent.mkdir(parents=True, exist_ok=True)

    # PyInstaller reads this back with ast.literal_eval, so it must be a plain
    # Python literal -- the VSVersionInfo(...) constructor call form it also
    # accepts would need the class in scope, which it does not have here.
    body = f"""# UTF-8
# Generated by build/make_version_info.py -- do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          "040904B0",
          [
            StringStruct("CompanyName", {COMPANY_NAME!r}),
            StringStruct("FileDescription", {FILE_DESCRIPTION!r}),
            StringStruct("FileVersion", {version!r}),
            StringStruct("InternalName", {ORIGINAL_FILENAME!r}),
            StringStruct("LegalCopyright", {COPYRIGHT!r}),
            StringStruct("OriginalFilename", {ORIGINAL_FILENAME!r}),
            StringStruct("ProductName", {PRODUCT_NAME!r}),
            StringStruct("ProductVersion", {version!r}),
          ],
        )
      ]
    ),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
"""
    out.write_text(body, encoding="utf-8")
    return str(out)


if __name__ == "__main__":
    print(version_file())
