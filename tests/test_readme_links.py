"""The READMEs must not point at anything that is not there.

Both READMEs are the front page of the project, and every link in them is a
promise: a screenshot of the interface, a design note, a pricing explanation.
A rename or a deleted file turns those into dead ends that nobody notices until
a reader clicks one.

This was written after the screenshots were re-taken for 0.0.4: the files are
regenerated by ``scripts/shot_readme.py``, so it is easy to rename or drop one
and leave a README pointing at a missing image. The check is cheap and catches
the whole class.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
READMES = [ROOT / "README.md", ROOT / "README.en.md"]

#: Markdown inline links and images: [text](target) / ![alt](target)
LINK = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)\)")

#: Section anchors are checked by the heading tests; external links are the
#: reader's problem, not ours.
SKIP_PREFIXES = ("http://", "https://", "mailto:", "#")


def _local_targets(text: str) -> list[str]:
    out = []
    for raw in LINK.findall(text):
        target = raw.split("#", 1)[0]          # drop a fragment
        if not target or target.startswith(SKIP_PREFIXES):
            continue
        out.append(target)
    return out


class ReadmeLinkTests(unittest.TestCase):
    def test_every_local_link_resolves(self) -> None:
        for readme in READMES:
            text = readme.read_text(encoding="utf-8")
            for target in _local_targets(text):
                path = (readme.parent / target).resolve()
                self.assertTrue(
                    path.exists(),
                    f"{readme.name} links to a missing file: {target}")

    def test_both_readmes_reference_the_same_screenshots(self) -> None:
        """Chinese and English must stay in step.

        They are separate files with separate image sets (app-zh-* / app-en-*),
        so this compares the *count* and the suffix pattern rather than names.
        """
        zh = [t for t in _local_targets(
            READMES[0].read_text(encoding="utf-8")) if "/docs/" in t]
        en = [t for t in _local_targets(
            READMES[1].read_text(encoding="utf-8")) if "/docs/" in t]
        self.assertEqual(len(zh), len(en),
                         f"README.md shows {len(zh)} images, "
                         f"README.en.md shows {len(en)}")
        for target in zh:
            self.assertIn("app-zh-", target)
        for target in en:
            self.assertIn("app-en-", target)

    def test_screenshots_are_not_stale_placeholders(self) -> None:
        """A zero-byte or tiny PNG means the capture silently failed."""
        for readme in READMES:
            for target in _local_targets(readme.read_text(encoding="utf-8")):
                if not target.endswith(".png"):
                    continue
                path = readme.parent / target
                self.assertGreater(
                    path.stat().st_size, 20_000,
                    f"{target} looks like a failed capture "
                    f"({path.stat().st_size} bytes)")


class ScreenshotScriptTests(unittest.TestCase):
    def test_capture_script_is_committed(self) -> None:
        """The images must be reproducible, not hand-taken one-offs."""
        script = ROOT / "scripts" / "shot_readme.py"
        self.assertTrue(script.is_file(),
                        "the README screenshots need a re-runnable script")
        body = script.read_text(encoding="utf-8")
        # It has to cover every image the READMEs reference.
        for name in ("app-{lang}-1.png", "app-{lang}-2.png",
                     "app-{lang}-3.png"):
            self.assertIn(name, body)


if __name__ == "__main__":
    unittest.main()
